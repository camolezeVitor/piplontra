import { ApparelSlot, Item, ItemRarity, WeaponType, createItem } from './models';

type R = ItemRarity;

const weapon = (label: string, weaponType: WeaponType, ammoType: string, damage: number, range: number, rate: number, weight: number, value: number, rarity: R): Item =>
    createItem('weapon', { label, weaponType, ammoType, damage, range, rate, weight, value, rarity });
const apparel = (label: string, apparelSlot: ApparelSlot, dr: number, er: number, rr: number, weight: number, value: number, rarity: R): Item =>
    createItem('apparel', { label, apparelSlot, dr, er, rr, weight, value, rarity });
const aid = (label: string, hp: number, rads: number, effect: string, weight: number, value: number, rarity: R): Item =>
    createItem('aid', { label, hp, rads, effect, weight, value, rarity });
const ammo = (label: string, weight: number, value: number, rarity: R): Item =>
    createItem('ammo', { label, weight, value, rarity });
const junk = (label: string, component: string, weight: number, value: number, rarity: R): Item =>
    createItem('junk', { label, component, weight, value, rarity });
const misc = (label: string, isQuest: boolean, weight: number, value: number, rarity: R): Item =>
    createItem('misc', { label, isQuest, weight, value, rarity });
const mod = (label: string, slot: string, weight: number, value: number, rarity: R): Item =>
    createItem('mod', { label, slot, weight, value, rarity });

